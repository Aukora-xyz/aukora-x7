/**
 * Generates `recovery-restore-page.script.mjs`: the restore page's browser script as ONE PLAIN STRING, made from
 * `recoveryRestoreKit` and `recoveryRestorePage` exactly as written. Run unbundled with Node:
 *   node deploy/cloudflare/src/recovery-restore-page.generate.mjs
 * Serializing functions at Worker runtime is wrong: Wrangler bundles with esbuild `keepNames`, which injects `__name`
 * calls that do not exist in the browser. A string literal passes through bundling untouched. The recovery-restore test
 * fails if the committed file differs from what this produces.
 * @module recovery-restore-page.generate
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { recoveryRestoreKit, recoveryRestorePage } from './recovery-restore.mjs'

/** The page script from the current sources. */
export const composeRecoveryRestorePageScript = () => `(${recoveryRestorePage.toString()})((${recoveryRestoreKit.toString()})())`

/** The generated module's full text. */
export const recoveryRestorePageScriptModule = () => '/** GENERATED by recovery-restore-page.generate.mjs from recovery-restore.mjs. Do not edit; regenerate. */\n'
  + `export const RECOVERY_RESTORE_PAGE_SCRIPT = ${JSON.stringify(composeRecoveryRestorePageScript())}\n`

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL('./recovery-restore-page.script.mjs', import.meta.url), recoveryRestorePageScriptModule())
}
