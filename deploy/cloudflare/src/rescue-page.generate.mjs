/**
 * Generates `rescue-page.script.mjs`: the `/rescue` page's browser script as ONE PLAIN STRING, made from `rescueKit` and
 * `rescuePage` exactly as written (Wrangler bundles with esbuild `keepNames`, which would inject `__name` into a function
 * serialized at runtime; a string literal passes through bundling untouched). The rescue-page test fails if the committed
 * file differs from what this produces.
 *   node deploy/cloudflare/src/rescue-page.generate.mjs                 writes rescue-page.script.mjs
 *   node deploy/cloudflare/src/rescue-page.generate.mjs --print-local [--settings] [--again]
 *       prints the kit + saveLocal() + the download, for a plain signed-in page's console (before any deploy); saved
 *       settings are left out unless --settings is given
 *   node deploy/cloudflare/src/rescue-page.generate.mjs --print-memory [--settings] [--again]
 *       prints the kit over `__X6_SERVICES__.fs`, for her worker's console; returns the Blob, its URL and the summary
 * The pack is said "saved" only after the kit has read the finished Blob back. Both console scripts keep the held pack
 * in `globalThis.__x61RescueHeld`, so a second paste in the same page is refused while a pack is held; a script printed
 * with --again releases the held pack and its URL first. The local script revokes its URL right after the click; the
 * memory script hands its URL out (there is no click in a worker) and the next run, or `kit.release()`, revokes it.
 * Both console scripts log and return counts and shapes only, never a key: the main thread is named by its session
 * folder's last two path parts, and nothing under her private folder is ever named. An error the kit did not expect is
 * caught and said in one line whose message has passed the same private-path redaction.
 * @module rescue-page.generate
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { rescueKit, rescuePage } from './rescue-kit.mjs'

/** The page script from the current sources. */
export const composeRescuePageScript = () => `(${rescuePage.toString()})((${rescueKit.toString()})({}))`

/** The generated module's full text. */
export const rescuePageScriptModule = () => '/** GENERATED by rescue-page.generate.mjs from rescue-kit.mjs. Do not edit; regenerate. */\n'
  + `export const RESCUE_PAGE_SCRIPT = ${JSON.stringify(composeRescuePageScript())}\n`

/** For a console on a plain page of her origin: build the pack and hand it over as one download. */
export const composeLocalConsoleScript = ({ settings = false, again = false } = {}) => '(async () => {\n'
  + '  const holder = globalThis.__x61RescueHeld || (globalThis.__x61RescueHeld = {})\n'
  + `  const kit = (${rescueKit.toString()})({ holder })\n`
  + '  let result\n'
  + `  try { result = await kit.saveLocal({ report: line => console.log(line), settings: ${settings === true}, again: ${again === true} }) }\n`
  + '  catch (error) { const line = kit.stoppedLine(error); console.log(line); return line }\n'
  + '  if (result.blob) {\n'
  + '    const url = kit.urlOf(result.blob)\n'
  + "    const anchor = document.createElement('a')\n"
  + '    anchor.href = url\n'
  + '    anchor.download = result.fileName\n'
  + '    document.body.appendChild(anchor)\n'
  + '    anchor.click()\n'
  + '    anchor.remove()\n'
  + '    kit.revokeUrl()\n'
  + '  }\n'
  + '  return [result.line].concat(result.plain).join("\\n")\n'
  + '})()\n'

/** For her worker's console: the same pack, rows taken from the tab's own file system (only read). */
export const composeMemoryConsoleScript = ({ settings = false, again = false } = {}) => '(async () => {\n'
  + '  const holder = globalThis.__x61RescueHeld || (globalThis.__x61RescueHeld = {})\n'
  + `  const kit = (${rescueKit.toString()})({ source: 'memory', fs: globalThis.__X6_SERVICES__.fs, holder })\n`
  + '  let result\n'
  + `  try { result = await kit.saveLocal({ report: line => console.log(line), settings: ${settings === true}, again: ${again === true} }) }\n`
  + '  catch (error) {\n'
  + '    const line = kit.stoppedLine(error)\n'
  + '    console.log(line)\n'
  + '    return { ok: false, complete: false, line, lines: [], id: null, fileName: null, blob: null, url: null }\n'
  + '  }\n'
  + '  const url = result.blob && typeof URL.createObjectURL === "function" ? kit.urlOf(result.blob) : null\n'
  + '  console.log([result.line].concat(result.plain).join("\\n"))\n'
  + '  return { ok: result.ok, complete: result.complete, line: result.line, lines: result.plain, id: result.id, fileName: result.fileName, blob: result.blob, url }\n'
  + '})()\n'

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [flag, ...extras] = process.argv.slice(2)
  const settings = extras.includes('--settings'), again = extras.includes('--again')
  const wellFormed = extras.every(extra => extra === '--settings' || extra === '--again') && new Set(extras).size === extras.length
  if (wellFormed && flag === '--print-local') process.stdout.write(composeLocalConsoleScript({ settings, again }))
  else if (wellFormed && flag === '--print-memory') process.stdout.write(composeMemoryConsoleScript({ settings, again }))
  else if (flag === undefined) writeFileSync(new URL('./rescue-page.script.mjs', import.meta.url), rescuePageScriptModule())
  else { process.stderr.write('usage: rescue-page.generate.mjs [--print-local | --print-memory] [--settings] [--again]\n'); process.exitCode = 2 }
}
