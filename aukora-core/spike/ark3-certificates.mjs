// Run from the lab root with 'one' or 'all'. The reference file supplies the
// coefficients and field operations. Lean independently verifies every witness.
import { codeRow, gfMul, gfInv } from '../reference/sealed-shards.mjs'
import { writeFileSync } from 'node:fs'

function inverse(rows) {
  const a = rows.map((r, i) => [
    ...codeRow(r, 4), ...Array.from({ length: 4 }, (_, j) => Number(i === j)),
  ])
  for (let j = 0; j < 4; j++) {
    const p = a.findIndex((row, i) => i >= j && row[j] !== 0)
    if (p === -1) throw new Error('singular minor ' + rows)
    ;[a[j], a[p]] = [a[p], a[j]]
    const k = gfInv(a[j][j])
    a[j] = a[j].map(v => gfMul(v, k))
    for (let i = 0; i < 4; i++) {
      if (i === j) continue
      const k = a[i][j]
      a[i] = a[i].map((v, c) => v ^ gfMul(k, a[j][c]))
    }
  }
  const bytes = a.flatMap(row => row.slice(4)).reverse()
  return '0x' + Buffer.from(bytes).toString('hex')
}

const mode = process.argv[2]
const header = 'import Ark3\n\nnamespace Aukora.Ark3\n\n'
if (mode === 'one') {
  const rows = [6, 7, 8, 9]
  const w = inverse(rows)
  const source = header + 'theorem lastFour : TwoSided (minor (6,7,8,9)) (entry ' +
    w + ') := check_spec _ _ |>.mp (by decide)\n#print axioms lastFour\n\nend Aukora.Ark3\n'
  writeFileSync('core/Ark3One.lean', source)
} else if (mode === 'all') {
  const records = []
  for (let d = 3; d < 10; d++)
    for (let c = 2; c < d; c++)
      for (let b = 1; b < c; b++)
        for (let a = 0; a < b; a++) {
          const rows = [a, b, c, d]
          records.push({ rows, w: inverse(rows) })
        }
  const certificate = ({ rows, w }) => {
    const name = 'cert' + rows.join('')
    return 'def ' + name + ' : Certificate := ⟨(' + rows.join(',') + '), ' + w + ', by decide⟩'
  }
  const names = records.map(({ rows }) => 'cert' + rows.join(''))
  let source = header + '-- The 40 bytes below are generated by the reference module’s codeRow.\n'
  const table = Array.from({ length: 10 }, (_, i) => '[' + [...codeRow(i, 4)].join(',') + ']').join(',')
  source += 'theorem matchesSourceRows : (List.range 10).map (fun i => axis.map (coeff i)) =\n'
  source += '  [' + table + '] := by decide\n\n'
  source += records.map(certificate).join('\n') + '\n\n'
  source += 'def certificates : List Certificate := [\n'
  for (let i = 0; i < names.length; i += 10)
    source += '  ' + names.slice(i, i + 10).join(', ') + (i + 10 === names.length ? ']\n\n' : ',\n')
  source += `def subsets : List Rows :=
  (List.range 10).flatMap fun d => (List.range d).flatMap fun c =>
    (List.range c).flatMap fun b => (List.range b).map fun a => (a,b,c,d)

set_option maxRecDepth 8192
set_option maxHeartbeats 2000000

theorem covers : certificates.map Certificate.rows = subsets := by decide
theorem count : subsets.length = 210 := by decide

theorem everyFour (a b c d : Nat) (hab : a < b) (hbc : b < c)
    (hcd : c < d) (hd : d < 10) :
    ∃ w : Nat, TwoSided (minor (a,b,c,d)) (entry w) := by
  have hs : (a,b,c,d) ∈ subsets := by
    exact List.mem_flatMap.mpr ⟨d, List.mem_range.mpr hd, List.mem_flatMap.mpr
      ⟨c, List.mem_range.mpr hcd, List.mem_flatMap.mpr
      ⟨b, List.mem_range.mpr hbc, List.mem_map.mpr ⟨a, List.mem_range.mpr hab, rfl⟩⟩⟩⟩
  rw [← covers] at hs
  obtain ⟨s, _, e⟩ := List.mem_map.mp hs
  exact ⟨s.inverse, e ▸ (check_spec _ _).mp s.verifies⟩

#print axioms matchesSourceRows
#print axioms actualParityEntries
#print axioms covers
#print axioms count
#print axioms everyFour
end Aukora.Ark3
`
  writeFileSync('core/Ark3All.lean', source)
} else throw new Error('expected one or all')
