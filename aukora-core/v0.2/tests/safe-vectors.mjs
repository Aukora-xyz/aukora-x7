function signedPolicy(tag,role,fields,active = first,generation = 0) {
  const hdr = h.header();
  const msg = cat(text('AUKORA/R9/'+role),keyFields(active),u64(generation),hdr,fields);
  const {edSig,mlSig} = dual(active,msg);
  return cat(Buffer.of(tag),hdr,fields,edSig,mlSig);
}
