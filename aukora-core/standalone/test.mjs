// End-to-end test of the adapter against the pinned v0.1 core. Run: node standalone/test.mjs
import { Core, newOwner } from './aukora.mjs';
let pass = 0, fail = 0; const check = (name, got, want = true) => { if (got === want) pass++; else { fail++; console.log('FAIL', name, 'got', got, 'want', want); } };
const owner = newOwner(), stranger = newOwner(); const c = await Core.load(); c.init(owner);
const pay = { payload: 'send the weekly report to the team', audience: 'mail', generation: 0, nonce: 1 };
check('speech is free', c.say('hello, this is the first line'));
check('act without approval is refused', c.act(pay), false);
check('approval signed by a stranger is refused', c.grant(stranger, pay), false);
check('approval signed by the owner is admitted', c.grant(owner, pay));
check('the approved act is admitted', c.act(pay));
check('the same approval cannot be used twice', c.act(pay), false);
check('a different payload was never approved', c.act({ ...pay, payload: 'send the weekly report to everyone' }), false);
check('outcome recorded', c.outcome(pay, 'confirmed'));
check('outcome reads back', JSON.stringify(c.outcomeOf(pay)), JSON.stringify({ result: 'confirmed', corrected: false }));
check('a second plain outcome is refused', c.outcome(pay, 'failed'), false);
check('a labelled correction is admitted', c.correctOutcome(pay, 'failed'));
check('the view shows it was corrected', JSON.stringify(c.outcomeOf(pay)), JSON.stringify({ result: 'failed', corrected: true }));
const timed = { payload: 'post the status page', audience: 'web', generation: 0, nonce: 2 };
check('timed approval admitted', c.grantUntil(owner, timed, c.seq + 3));
check('cancel that approval', c.revoke(owner, timed));
check('a cancelled approval admits nothing', c.act(timed), false);
const late = { payload: 'archive last month', audience: 'files', generation: 0, nonce: 3 };
check('timed approval admitted (2)', c.grantUntil(owner, late, c.seq + 2));
c.say('one'); c.say('two'); c.say('three');
check('an expired approval admits nothing', c.act(late), false);
check('a stranger cannot move the danger threshold', c.setThreshold(stranger, 200), false);
check('threshold unchanged', c.threshold(), 0);
const next = newOwner(); const again = { payload: 'after the key change', audience: 'mail', generation: 1, nonce: 4 };
check('a stranger cannot change the keys', c.rebind(stranger, next), false);
check('the owner changes the keys', c.rebind(owner, next));
check('the old keys no longer approve', c.grant(owner, again), false);
check('the new keys approve', c.grant(next, again));
check('and that approval works', c.act(again));
const head = c.headHex(), record = c.exportRecord(), n = c.frames.length;
const d = await Core.load(); check('replay gives the same head', await d.replay(record), head);
const lines = record.trim().split('\n');
const tamper = async (name, edit) => { const e = await Core.load(); let r; try { r = await e.replay(edit([...lines]).join('\n')); } catch (x) { r = 'refused'; } check(name, r === 'refused' || r !== head); return r; };
check('changed word in an early line is caught', await tamper('edit', l => { l[2] = l[2].slice(0, -2) + (l[2].endsWith('65') ? '66' : '65'); return l; }), 'refused');
check('a dropped middle line is caught', await tamper('drop', l => { l.splice(4, 1); return l; }), 'refused');
check('two swapped lines are caught', await tamper('swap', l => { [l[3], l[4]] = [l[4], l[3]]; return l; }), 'refused');
const cut = await tamper('cut', l => l.slice(0, -1)); check('a dropped LAST line replays cleanly but the head differs (known limit: someone must remember the head)', cut !== 'refused' && cut !== head);
let unpinned; try { await Core.load(new URL('./aukora.mjs', import.meta.url).pathname); unpinned = 'loaded'; } catch { unpinned = 'refused'; } check('a file that is not a pinned core is not loaded', unpinned, 'refused');
console.log(`${pass} passed, ${fail} failed; record ${n} lines; head ${head.slice(0, 16)}…; core ${c.coreDigest.slice(0, 16)}…`);
process.exit(fail ? 1 : 0);
