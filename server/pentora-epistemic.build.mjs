/** Generate the bounded observer's exact rows from the pinned Pentora carrier.
 * Run without flags to check; --write refreshes the derived browser table. */
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { evaluationMatrix, GEOMETRY_SHA256, NODES, COMPONENTS, SLOTS, SCALE } from './pentora-codec.build.mjs'

const path = new URL('../packages/experimental/webworker-runtime/src/x6/pentora-epistemic-table.ts', import.meta.url)
const { A, radii } = evaluationMatrix()
if (A.length !== NODES * COMPONENTS || radii.length !== NODES || COMPONENTS !== 8 || SLOTS !== 72) throw new Error('observer profile changed')
const P = 2147483647n
const mod = n => (n % P + P) % P
function invert(n) {
  let a = mod(n), b = P - 2n, value = 1n
  while (b) {
    if (b & 1n) value = mod(value * a)
    a = mod(a * a)
    b >>= 1n
  }
  return value
}
const corners = radii.flatMap((radius, index) => radius === 3 ? [index] : [])
if (corners.length !== 20) throw new Error('observer corner count changed')
const divisor = SCALE * BigInt(corners.length)
const invDivisor = invert(divisor)
const sums = Array.from({ length: 8 }, (_, chan) => Array.from({ length: SLOTS }, (_, col) =>
  corners.reduce((total, node) => total + A[node * COMPONENTS + chan][col], 0n)))
if (sums.some((row, i) => i !== 0 && i !== 4 && row.some(n => n !== 0n))) throw new Error('unexpected radical in mean')
const meanA = sums[0].map((a, i) => Number(mod((a - sums[4][i]) * invDivisor)))
const meanB = sums[4].map(b => Number(mod(2n * b * invDivisor)))
const rows = []
for (let i = 0; i < A.length; i++) {
  const coefficients = A[i]
  if (coefficients.length !== SLOTS) throw new Error('observer row width changed')
  const termBytes = []
  for (let j = 0; j < SLOTS; j++) {
    const value = coefficients[j]
    if (value === 0n) continue
    if (value < -32768n || value > 32767n) throw new Error('observer term overflow')
    const u = Number(value) & 65535
    termBytes.push(j, u & 255, u >> 8)
  }
  if (termBytes.length > 0) rows.push([Math.floor(i / COMPONENTS), i % COMPONENTS, Buffer.from(termBytes).toString('base64')])
}
if (rows.length !== 380) throw new Error('active row budget changed')
const doc = { geometrySha256: GEOMETRY_SHA256, scale: Number(SCALE), representation: 'i16le-sparse', field: Number(P), rows, meanA, meanB }
const sha = createHash('sha256').update(JSON.stringify(doc)).digest('hex')
const format = row => Array.from({ length: Math.ceil(row.length / 12) }, (_, i) => '  ' + row.slice(i * 12, i * 12 + 12).join(', ') + ',').join('\n')
const out = `// Generated by server/pentora-epistemic.build.mjs. Do not edit.
export const PENTORA_PROFILE_ID = 'pentora110-qphi72-fp2147483647-v1'
export const PENTORA_MATRIX_SHA256 = '${sha}'
export const PENTORA_GEOMETRY_SHA256 = '${GEOMETRY_SHA256}'
export const PENTORA_SCALE = ${SCALE}
export const PENTORA_MEAN_A = [
${format(meanA)}
] as const
export const PENTORA_MEAN_B = [
${format(meanB)}
] as const
export const PENTORA_ACTIVE_ROWS: ReadonlyArray<readonly [number, number, string]> = [
${rows.map(row => '  ' + JSON.stringify(row) + ',').join('\n')}
]
`
if (process.argv.length === 3 && process.argv[2] === '--write') writeFileSync(path, out)
else if (process.argv.length !== 2 || readFileSync(path, 'utf8') !== out) throw new Error('Pentora observer table differs from pinned geometry')
